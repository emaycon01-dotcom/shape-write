export function cursosPorModalidade(m: Modalidade): string[] {
  if (m === "bacharelado") return CURSOS_BACHARELADO;
  if (m === "licenciatura") return CURSOS_LICENCIATURA;
  return CURSOS_TECNOLOGO;
}

/** Nome do curso como aparece no corpo do diploma (página 1). */
export function nomeCursoCompleto(m: Modalidade, curso: string): string {
  if (m === "tecnologo") return `CURSO SUPERIOR DE TECNOLOGIA EM ${curso}`;
  if (m === "licenciatura") return `CURSO DE LICENCIATURA EM ${curso}`;
  return `CURSO DE ${curso}`;
}

export function tituloConferido(m: Modalidade): string {
  return MODALIDADES.find((x) => x.id === m)?.titulo || "BACHAREL (A)";
}

